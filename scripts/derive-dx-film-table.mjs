// Derives negative2positive/src/app/dxFilmTable.js from The Big Film Database
// (https://github.com/dxdatabase/Open-source-film-database, CC BY-SA 4.0).
//
// Usage:
//   node scripts/derive-dx-film-table.mjs [path/to/film_database.csv]
// Without a path the CSV is downloaded from the GitHub repository.
//
// The film edge barcode carries DX part 1 (0-127) and part 2 (0-15); the
// database keys films by the four-digit "DX extract", which is part1 * 16 +
// part2. One extract can map to several trade names (the same emulsion sold
// in different markets), so every name is kept and a primary one is chosen
// by a small scoring heuristic that favours well-known, current products.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(here, '..', 'negative2positive', 'src', 'app', 'dxFilmTable.js');
const SOURCE_URL = 'https://raw.githubusercontent.com/dxdatabase/Open-source-film-database/main/film_database.csv';

const PREFERRED = [
  'ULTRA MAX', 'ULTRAMAX', 'GOLD', 'PORTRA', 'EKTAR', 'COLORPLUS', 'COLOR PLUS', 'PRO IMAGE',
  'SUPERIA', 'FUJICOLOR', 'C200', 'PRO 400H', 'PRO 160', 'REALA', 'NATURA', 'VENUS',
  'VISION3', 'CINESTILL', 'TRI-X', 'T-MAX', 'TMAX', 'HP5', 'FP4', 'DELTA', 'PAN F', 'XP2',
  'KENTMERE', 'FOMAPAN', 'APX', 'ACROS', 'VISTA', 'PROVIA', 'VELVIA', 'ASTIA', 'SENSIA',
  'EKTACHROME', 'KODACHROME', 'ELITE CHROME', 'PHOENIX', 'LOMOGRAPHY', 'HARMAN'
];
const PENALISED = ['?', 'uncertain', 'disposable', 'bulk', 'respool', 'reload'];

async function loadCsv(path) {
  if (path) return readFileSync(path, 'utf8');
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`download failed: ${response.status}`);
  return await response.text();
}

function cleanName(raw) {
  let name = raw.replace(/\s+/g, ' ').trim();
  name = name.replace(/\s*#\S+/g, '');
  name = name.replace(/\s*[–-]\s*Code\s*:?\s*\d.*$/i, '');
  name = name.replace(/\s*\((?:gen\.?|generation)[^)]*\)/gi, '');
  name = name.replace(/["“”]/g, '').trim();
  return name.replace(/[\s–-]+$/g, '');
}

function scoreName(name, reliability) {
  const upper = name.toUpperCase();
  let score = 0;
  for (const word of PREFERRED) if (upper.includes(word)) score += 10;
  for (const word of PENALISED) if (upper.includes(word.toUpperCase())) score -= 8;
  if (/\bfilm\b/i.test(name)) score += 2;
  if (Number.isFinite(reliability)) score += reliability;
  score -= name.length / 40;
  return score;
}

const csv = await loadCsv(process.argv[2]);
const lines = csv.split(/\r?\n/).filter(Boolean);
const header = lines.shift().split(';');
const col = (label) => header.indexOf(label);
const iExtract = col('DX extract');
const iName = col('Name');
const iReliability = col('reliability');
const iManufacturer = col('Manufacturer');

const byExtract = new Map();
for (const line of lines) {
  const cells = line.split(';');
  const extract = (cells[iExtract] || '').trim();
  if (!/^\d{1,4}$/.test(extract)) continue;
  const value = Number(extract);
  if (value < 0 || value > 2047) continue;
  const name = cleanName(cells[iName] || '');
  if (!name) continue;
  const reliability = Number(cells[iReliability]);
  const manufacturer = (cells[iManufacturer] || '').trim();
  const list = byExtract.get(value) || [];
  if (!list.some((entry) => entry.name.toLowerCase() === name.toLowerCase())) {
    list.push({ name, reliability: Number.isFinite(reliability) ? reliability : null, manufacturer });
  }
  byExtract.set(value, list);
}

const rows = [];
for (const [extract, entries] of [...byExtract.entries()].sort((a, b) => a[0] - b[0])) {
  const ranked = entries
    .map((entry) => ({ ...entry, score: scoreName(entry.name, entry.reliability) }))
    .sort((a, b) => b.score - a.score);
  const names = ranked.slice(0, 5).map((entry) => entry.name);
  rows.push([extract, names]);
}

const body = rows.map(([extract, names]) => `  [${extract}, ${JSON.stringify(names)}]`).join(',\n');
const output = `// Generated by scripts/derive-dx-film-table.mjs. Do not edit by hand.
//
// Source: The Big Film Database (dxdatabase) © 2018 by Dxdatabase,
// https://github.com/dxdatabase/Open-source-film-database
// Licensed under Creative Commons Attribution-ShareAlike 4.0 International
// (https://creativecommons.org/licenses/by-sa/4.0/). This table is a
// transformed excerpt (DX extract -> film names) and is distributed under
// the same licence; the rest of this application is MIT licensed.
//
// Each row is [dxExtract, names]. dxExtract = DX part 1 * 16 + DX part 2, the
// four-digit number also found in the cassette barcode. Names are ordered
// with the most recognisable trade name first.

export const DX_FILM_TABLE_SOURCE = 'The Big Film Database (CC BY-SA 4.0)';

export const DX_FILM_TABLE = [
${body}
];
`;
writeFileSync(OUTPUT, output);
console.log(`wrote ${rows.length} DX extracts to ${OUTPUT}`);
